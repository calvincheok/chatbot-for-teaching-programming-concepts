"""Build the GitHub Pages version in docs/ from the Flask version.

GitHub Pages can only host static files, so docs/ runs the teaching engine
in the browser. To keep the two versions the same, this script copies or
generates every shared part from the Python project:

    docs/index.html     from templates/index.html (with the browser scripts)
    docs/chat.js        copied from static/chat.js
    docs/chat.css       copied from static/chat.css
    docs/js/content.js  topics, prompts, engine settings and fake tutor
                        content, taken from the Python modules
    tests/prompt_samples.json
                        the full system prompt for every task and topic, so
                        the Node tests can check the browser builds the same ones

The browser-only logic (docs/js/engine.js, prompts.js, fake-provider.js,
storage.js, backend-local.js) is written by hand and mirrors the Python code.

Run after changing the Python content, prompts or the page:
    python build_pages.py           write docs/
    python build_pages.py --check   only report whether the generated files are up to date
"""

from __future__ import annotations

import json
import os
import re
import sys

from teaching import engine, prompts
from teaching.concepts import CONCEPTS
from teaching.providers import fake_content

HERE = os.path.dirname(os.path.abspath(__file__))

BROWSER_SCRIPTS = ["js/content.js", "js/prompts.js", "js/fake-provider.js", "js/storage.js", "js/engine.js", "js/backend-local.js"]


def _read(*parts: str) -> str:
    with open(os.path.join(HERE, *parts), encoding="utf-8") as f:
        return f.read()


def _js_template(text: str) -> str:
    """Python str.format templates use {{ }} for a literal brace; the browser version uses single braces."""
    return text.replace("{{", "{").replace("}}", "}")


def content_js() -> str:
    data = {
        "CONCEPTS": CONCEPTS,
        "PROMPTS": {
            "LEVELS": prompts.LEVELS,
            "STRATEGIES": prompts.STRATEGIES,
            "BASE_RULES": prompts.BASE_RULES,
            "TASKS": {k: _js_template(v) for k, v in prompts.TASKS.items()},
            "EXPERIENCE_FOCUS": prompts.EXPERIENCE_FOCUS,
        },
        "ENGINE": {
            "DIAGNOSTIC_QUESTIONS": engine.DIAGNOSTIC_QUESTIONS,
            "HISTORY_LIMIT": engine.HISTORY_LIMIT,
            "MAX_MESSAGE_LENGTH": engine.MAX_MESSAGE_LENGTH,
            "CHECKS_NEEDED": engine.CHECKS_NEEDED,
            "MAX_CHECKS": engine.MAX_CHECKS,
            "WELCOME": engine.WELCOME,
            "COMPLETE_PASSED": engine.COMPLETE_PASSED,
            "COMPLETE_REVIEW": engine.COMPLETE_REVIEW,
        },
        "FAKE": {
            "PATTERNS": fake_content.PATTERNS,
            "TOPICS": fake_content.TOPICS,
            "UNKNOWN_QUESTION": fake_content.UNKNOWN_QUESTION,
        },
    }
    lines = [
        "/* GENERATED by build_pages.py from the Python project. Do not edit by hand:",
        "   change teaching/concepts.py, prompts.py, engine.py or providers/fake_content.py,",
        "   then run `python build_pages.py`. */",
        '"use strict";',
        "var PyTutor = window.PyTutor || (window.PyTutor = {});",
    ]
    for name, value in data.items():
        lines.append(f"PyTutor.{name} = {json.dumps(value, ensure_ascii=False, indent=2)};")
    return "\n".join(lines) + "\n"


def index_html() -> str:
    html = _read("templates", "index.html")
    html = re.sub(r"\{\{ url_for\('static', filename='([^']+)'\) \}\}", r"\1", html)
    scripts = "\n  ".join(f'<script src="{src}"></script>' for src in BROWSER_SCRIPTS)
    html, count = re.subn(r"<!-- backend -->.*?<!-- /backend -->", f"<!-- browser engine -->\n  {scripts}", html, flags=re.S)
    if count != 1 or "{{" in html or "{%" in html:
        raise SystemExit("templates/index.html changed in a way build_pages.py doesn't understand.")
    doctype, rest = html.split("\n", 1)
    return doctype + "\n<!-- GENERATED by build_pages.py from templates/index.html. Do not edit by hand. -->\n" + rest


def prompt_samples() -> str:
    fields = {"number": 2, "total": 3, "focus": "FOCUS", "level_description": prompts.LEVELS["beginner"],
              "strategy": prompts.STRATEGIES["beginner"], "gaps": "GAPS", "attempt": 1}
    samples = []
    for concept_id, concept in CONCEPTS.items():
        if concept["enabled"]:
            for task in prompts.TASKS:
                samples.append({"task": task, "concept": concept_id, "fields": fields,
                                "prompt": prompts.system_prompt(task, concept, **fields)})
    return json.dumps(samples, ensure_ascii=False, indent=1) + "\n"


def outputs() -> dict[str, str]:
    """Every generated file, by path relative to the project folder."""
    return {
        "docs/index.html": index_html(),
        "docs/chat.js": "/* GENERATED by build_pages.py: a copy of static/chat.js. Do not edit by hand. */\n" + _read("static", "chat.js"),
        "docs/chat.css": "/* GENERATED by build_pages.py: a copy of static/chat.css. Do not edit by hand. */\n" + _read("static", "chat.css"),
        "docs/js/content.js": content_js(),
        "docs/.nojekyll": "",
        "tests/prompt_samples.json": prompt_samples(),
    }


def stale() -> list[str]:
    out = []
    for name, text in outputs().items():
        path = os.path.join(HERE, name)
        if not os.path.exists(path) or _read(name) != text:
            out.append(name)
    return out


def main() -> None:
    if "--check" in sys.argv:
        names = stale()
        print("Generated files are up to date." if not names else "Out of date: " + ", ".join(names) + ". Run: python build_pages.py")
        sys.exit(1 if names else 0)
    for name, text in outputs().items():
        path = os.path.join(HERE, name)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote " + name)


if __name__ == "__main__":
    main()
